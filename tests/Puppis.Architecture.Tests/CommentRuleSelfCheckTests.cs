namespace Puppis.Architecture.Tests;

public sealed class CommentRuleSelfCheckTests
{
    [Theory]
    [InlineData("int a; // why", 1)]
    [InlineData("int a;\n/// <summary>x</summary>\nint b;", 2)]
    [InlineData("int a;\nint b; /* why */ int c;", 2)]
    [InlineData("int a;\n/* one\n two */\nint b;", 2)]
    [InlineData("int a;\n\n\n// why", 4)]
    public void ACommentIsReportedOnTheLineItStartsOn(string source, int line)
    {
        Assert.Equal([line], CommentRules.CommentsIn(source).Select(comment => comment.Line));
    }

    [Theory]
    [InlineData("string a = \"http://host\";")]
    [InlineData("string a = \"a \\\" // b\";")]
    [InlineData("string a = @\"a \"\" // b\";")]
    [InlineData("string a = $\"{x}//{y}\";")]
    [InlineData("string a = $\"{(x ? \"//\" : \"\")}\";")]
    [InlineData("string a = $\"{{ // }}\";")]
    [InlineData("string a = \"\"\"a // b \" \"\" c\"\"\";")]
    [InlineData("string a = $$\"\"\"{{x}} // {y}\"\"\";")]
    [InlineData("string a = $$\"\"\"{{(x ? \"\"\"\" : \"//\")}}\"\"\";")]
    [InlineData("char a = '\"'; string b = \"// \";")]
    [InlineData("char a = '\\''; string b = \"// \";")]
    [InlineData("string a = \"\"; string b = \"//\";")]
    public void SlashesInsideALiteralAreNotAComment(string source)
    {
        Assert.Empty(CommentRules.CommentsIn(source));
    }

    [Theory]
    [InlineData("string a = \"x\"; // why", 1)]
    [InlineData("string a = $\"{x}\"; // why", 1)]
    [InlineData("string a = \"\"\"x\"\"\"; // why", 1)]
    [InlineData("char a = '\"'; // why", 1)]
    [InlineData("string a = @\"x\"; /* why */", 1)]
    public void ACommentAfterALiteralIsStillReported(string source, int expected)
    {
        Assert.Equal(expected, CommentRules.CommentsIn(source).Count);
    }

    [Theory]
    [InlineData("// <auto-generated/>\nint a;")]
    [InlineData("// <autogenerated />\nint a;")]
    [InlineData("// csharpier-ignore\nint a;")]
    public void ADirectiveAToolReadsIsNotReported(string source)
    {
        Assert.Empty(CommentRules.CommentsIn(source));
    }

    [Fact]
    public void AFolderHoldingACommentIsReportedByFileAndLine()
    {
        DirectoryInfo held = Directory.CreateTempSubdirectory("puppis-comment-rule-");

        try
        {
            Directory.CreateDirectory(Path.Combine(held.FullName, "src"));
            Directory.CreateDirectory(Path.Combine(held.FullName, "tests"));
            File.WriteAllText(Path.Combine(held.FullName, "src", "Clean.cs"), "int a;\n");
            File.WriteAllText(Path.Combine(held.FullName, "tests", "Noisy.cs"), "int a;\n// why\n");

            Assert.Equal(["tests/Noisy.cs:2"], CommentRules.PlacesThatCarryAComment(held.FullName));
        }
        finally
        {
            held.Delete(recursive: true);
        }
    }
}
